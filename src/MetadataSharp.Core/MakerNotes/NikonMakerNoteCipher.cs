internal static class NikonMakerNoteCipher
{
    /// <summary>Returns a decrypted copy of <paramref name="data"/>, leaving the first <paramref name="start"/> bytes as they are.</summary>
    internal static byte[] Decrypt(ReadOnlySpan<byte> data, int start, uint shutterCount, uint serial)
    {
        byte[] copy = data.ToArray();
        byte key = 0;
        for (int i = 0; i < 4; i++)
            key ^= (byte)(shutterCount >> (i * 8));
        byte ci = Table0[(int)(serial & 0xFF)];
        byte cj = Table1[key];
        byte ck = 0x60;
        for (int i = start; i < copy.Length; i++)
        {
            cj = (byte)(cj + ci * ck++);
            copy[i] ^= cj;
        }
        return copy;
    }

    /// <summary>
    /// The serial key: the serial number tag read as an unsigned decimal number, or, when it is not one,
    /// 0x22 for a D50 and 0x60 for any other model. Null when the model is unknown as well.
    /// </summary>
    internal static uint? SerialKey(ReadOnlySpan<byte> serialNumber, ReadOnlySpan<byte> model)
    {
        string text = Encoding.ASCII.GetString(serialNumber).TrimEnd('\0').Trim();
        if (uint.TryParse(text, NumberStyles.None, CultureInfo.InvariantCulture, out uint serial))
            return serial;
        if (model.IsEmpty)
            return null;
        return model.IndexOf("D50"u8) >= 0 ? 0x22u : 0x60u;
    }

