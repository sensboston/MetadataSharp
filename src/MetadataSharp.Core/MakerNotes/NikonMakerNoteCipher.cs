/// <summary>
/// The byte stream cipher of some Nikon3 array tags. Its key is the camera serial number (tag 0x001D)
/// and the shutter count (tag 0x00A7); bytes before the layout's start offset are not encrypted.
/// Two fixed 256-byte substitution tables seed it.
