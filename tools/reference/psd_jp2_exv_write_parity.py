#!/usr/bin/env python3
"""Bidirectional common-metadata write parity for PSD, JP2 and EXV against pinned Exiv2.

PSD's documented Exiv2 capability deliberately excludes ICC; the shared PSD gate therefore
compares EXIF/IPTC/XMP only. JP2 additionally compares exact ICC bytes in both write directions.
EXV ICC creation/read-back remains covered by MetadataSharp's format tests; Exiv2's binary ICC
print path does not recognize ICC in the authored EXV container. This is a narrow interoperability
gate, not whole-format equivalence.
"""
from __future__ import annotations

import argparse
import hashlib
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


OUR_EXPECTED = {
    "Exif.Image.Make": "TestCompany",
    "Iptc.Application2.Headline": "MSParity",
    "Xmp.xmp.CreatorTool": "MSParity",
}
EXIV2_EXPECTED = {
    "Exif.Image.Make": "Exiv2Make",
    "Iptc.Application2.Headline": "Exiv2Headline",
    "Xmp.xmp.CreatorTool": "Exiv2Creator",
}
FORMATS = (
    ("psd", ".psd", False),
    ("jp2", ".jp2", True),
    ("exv", ".exv", False),
)


class ParityError(RuntimeError):
    pass


def run(argv: list[str], *, cwd: Path | None = None, input_text: str | None = None) -> bytes:
    result = subprocess.run(argv, cwd=cwd, input=None if input_text is None else input_text.encode(),
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
    if result.returncode:
        raise ParityError(f"command failed ({result.returncode}): {shlex.join(argv)}\n"
                          f"stdout: {result.stdout[:1000]!r}\nstderr: {result.stderr[-3000:]!r}")
    return result.stdout


def check_exiv2_read(exiv2: list[str], image: Path, *, icc: bool, profile: bytes | None) -> None:
    printed = run(exiv2 + ["-Pkycvt", str(image)]).decode("utf-8", errors="replace")
    for key, value in OUR_EXPECTED.items():
        if not any(key in line and value in line for line in printed.splitlines()):
            raise ParityError(f"Exiv2 did not report the expected {key}={value} in {image.name}:\n{printed}")
    if icc:
        actual = run(exiv2 + ["-pC", str(image)])
        if profile is None or actual != profile:
            raise ParityError(f"Exiv2 ICC bytes differ for {image.name}: "
                              f"got {len(actual)} bytes, expected {0 if profile is None else len(profile)}")


def check_dump(dump: list[str], image: Path, *, icc: bool, profile: bytes | None) -> None:
    printed = run(dump + [str(image)]).decode("utf-8", errors="replace")
    for key, value in EXIV2_EXPECTED.items():
        if not any(f"\t{key}\t" in line and value in line for line in printed.splitlines()):
            raise ParityError(f"MetadataSharp did not report the expected {key}={value} in {image.name}:\n{printed}")
    if icc:
        records = run(dump + ["--icc", str(image)]).decode("utf-8", errors="replace")
        digest = hashlib.md5(profile or b"").hexdigest()
        expected = f"ICC\t{len(profile or b'')}\t{digest}"
        if expected not in records:
            raise ParityError(f"MetadataSharp ICC result differs for {image.name}; wanted {expected!r}, got {records!r}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="files generated by ReferenceFixture")
    parser.add_argument("--exiv2", required=True, help="pinned Exiv2 executable")
    parser.add_argument("--dump-command", required=True, help="MetadataSharp.Dump command and arguments")
    args = parser.parse_args()
    root = args.directory.resolve()
    exiv2 = shlex.split(args.exiv2)
    dump = shlex.split(args.dump_command)
    if not exiv2 or not dump:
        raise ParityError("both tool commands must be nonempty")
    profile = (root / "profile.icc").read_bytes()
    passed = 0

    # MetadataSharp-authored outputs must be consumable by Exiv2. The binary ICC assertion is kept
    # to JP2; PSD and EXV ICC are independently pinned by MetadataSharp's format-specific tests.
    for name, extension, supports_icc in FORMATS:
        image = root / f"ours-{name}{extension}"
        check_exiv2_read(exiv2, image, icc=supports_icc, profile=profile if supports_icc else None)
        passed += 1

    # Exiv2-authored outputs must be consumable by MetadataSharp. Each run starts from an untouched
    # base file; ICC insert is separate because Exiv2's profile option reads a sidecar named for the
    # target stem. PSD has no ICC operation in Exiv2 0.28.9's documented format matrix.
    with tempfile.TemporaryDirectory(prefix="metadatasharp-exiv2-write-") as temporary:
        work = Path(temporary)
        for name, extension, supports_icc in FORMATS:
            target = work / f"theirs-{name}{extension}"
            shutil.copyfile(root / f"base-{name}{extension}", target)
            if supports_icc:
                sidecar = work / f"{target.stem}.icc"
                sidecar.write_bytes(profile)
                run(exiv2 + ["-iC", "-l", str(work), "in", str(target)])
            run(exiv2 + ["-m", str(root / "modify.txt"), "mo", str(target)])
            check_dump(dump, target, icc=supports_icc, profile=profile if supports_icc else None)
            passed += 1
    print(f"PSD/JP2/EXV bidirectional write parity: {passed} checks passed; "
          "EXIF/IPTC/XMP all formats, exact ICC JP2; PSD/EXV ICC stays on MetadataSharp format tests.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ParityError as error:
        message = str(error).replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
        print(f"write parity failed: {error}", file=sys.stderr)
        print(f"::error title=PSD JP2 EXV write parity::{message}", file=sys.stderr)
        raise SystemExit(1)
